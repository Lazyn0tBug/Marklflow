/**
 * **目标现在是什么状态** ✓：**一个封闭的小集合** ✓（设计 §6.1 ✓）。
 *
 * **原生侧归类** ✓ ⇒ ⇒ 应用侧只按状态选处理 ✓ ⇒ ⇒ **检测与处理分开** ✓ ⇒ ⇒
 * **不是每个状态各写一堆判断** ✓ ⇒ ⇒ **一处分类，一处处理** ✓。
 *
 * **检测与写回共用这一个集合** ✓ ⇒ ⇒ **一处定义** ✓ ⇒ ⇒
 * **那两条分支因此走得到** ✓ ⇒ ⇒ **"目标没了"不用一个报错来说** ✓（§6.1 ✓）。
 *
 * - **ready** ✓：在、还是那一版、可以写 ✓；
 * - **changed** ✓：在、但被外部改过 ✓ ⇒ ⇒ 交给用户决定 ✓；
 * - **missing** ✓：不在了 ✓ ⇒ ⇒ 提示是否继续 ✓；
 * - **unwritable** ✓：在、但写不进去 ✓ ⇒ ⇒ 提示是否另存 ✓；
 * - **invalid** ✓：授权没了 ✓ ⇒ ⇒ 与写不进去同一支 ✓。
 */
export type TargetStatus = 'ready' | 'changed' | 'missing' | 'unwritable' | 'invalid';
